// Generates the files this package shares with the Yap desktop app, so the
// speech model pin and the text cleanup have ONE source: desktop/.
// Run before packing or publishing (npm run sync). Never edit the outputs.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const desktop = path.join(root, '..', 'desktop');
const header = '// GENERATED by scripts/sync.mjs from the Yap desktop app. Do not edit.\n';
if (!fs.existsSync(path.join(desktop, 'native-speech.json'))) {
  console.log('standalone checkout: using the committed src/model.json, src/polish.js and test fixture');
  process.exit(0);
}

const speech = JSON.parse(fs.readFileSync(path.join(desktop, 'native-speech.json'), 'utf8'));
const { model, revision, cacheDirectory, files, license, attribution } = speech.windows;
const pin = { engine: speech.windows.engine, model, revision, cacheDirectory, files, license, attribution,
  sampleRate: speech.sampleRate, languages: speech.languages, runtime: { engine: 'sherpa-onnx', version: speech.windows.runtime.version } };
fs.writeFileSync(path.join(root, 'src', 'model.json'), JSON.stringify(pin, null, 2) + '\n');

const polish = fs.readFileSync(path.join(desktop, 'polish.mjs'), 'utf8');
fs.writeFileSync(path.join(root, 'src', 'polish.js'), header + polish);

fs.mkdirSync(path.join(root, 'test', 'fixtures'), { recursive: true });
fs.copyFileSync(path.join(desktop, 'tests', 'fixtures', 'sandbox-dictation.wav'), path.join(root, 'test', 'fixtures', 'sandbox-dictation.wav'));

const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
const dep = pkg.dependencies['sherpa-onnx-node'];
if (dep !== pin.runtime.version) throw new Error(`sherpa-onnx-node ${dep} must match the desktop runtime ${pin.runtime.version}`);
console.log(`synced model ${model}@${revision.slice(0, 7)} and polish.js`);
